export function t(key: string, locale: Locale = 'en', params?: Record<string, string | number>): string {
  let text = translations[locale]?.[key] || translations.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}

export function useTranslation(locale: Locale = 'en') {
  return { t: (key: string, params?: Record<string, string | number>) => t(key, locale, params) };
}
